"""
Standalone final GIS evaluation runner for Approach 2 - Road Extraction.

Purpose
-------
Evaluate an already-generated Road prediction against the official
independent held-out Ground Truth WITHOUT rerunning the neural network.

Typical use
-----------
Prediction already exists
        ↓
Official independent test raster
        +
Official held-out Road Ground Truth
        ↓
Strict GIS polygon evaluation
        ↓
IoU / Precision / Recall / F1

Important
---------
This module performs NO:

- training
- inference
- threshold search
- post-processing search
- Optuna
- model selection
- source-specific retuning

For Satellite, the official independent pair is resolved from the
project configuration:

    SatelliteTesingZone
    Road_Test_Label
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Dict, Optional

from src.evaluation.gis_evaluation import (
    evaluate_polygon_prediction,
)

from src.final_test import (
    resolve_final_test_source,
    resolve_output_geodatabase,
)

from src.pipeline.final_settings import (
    load_frozen_final_settings,
)

from src.utils import (
    load_paths_config,
    load_test_zone_config,
    save_json,
)


# ---------------------------------------------------------------------
# Prediction discovery
# ---------------------------------------------------------------------

def load_prediction_from_final_inference(
    context: Dict[str, Any],
    source_name: str,
) -> str:
    """
    Retrieve the Road polygon feature class generated by the final
    inference stage.

    Expected file
    -------------
    outputs/experiments/<experiment_id>/final_test/<source>/
        final_inference_summary.json
    """

    source_name = str(
        source_name
    ).lower()

    summary_path = (
        Path(
            context[
                "output_folder"
            ]
        )
        / "final_test"
        / source_name
        / "final_inference_summary.json"
    )

    if not summary_path.exists():

        raise FileNotFoundError(
            "Final inference summary does not exist:\n"
            f"{summary_path}\n\n"
            "Either run final inference first or provide an explicit "
            "prediction feature class."
        )

    with summary_path.open(
        "r",
        encoding="utf-8",
    ) as file:

        data = json.load(
            file
        )

    prediction_fc = data.get(
        "polygon_feature_class"
    )

    if not prediction_fc:

        raise KeyError(
            "final_inference_summary.json does not contain "
            "'polygon_feature_class'."
        )

    return str(
        prediction_fc
    )


# ---------------------------------------------------------------------
# ArcGIS existence check
# ---------------------------------------------------------------------

def _arcgis_exists(
    dataset: str,
) -> bool:
    """
    Check an ArcGIS dataset.
    """

    try:
        import arcpy

    except ImportError as exc:

        raise RuntimeError(
            "Standalone GIS evaluation requires the ArcGIS Pro "
            "Python environment."
        ) from exc

    return bool(
        arcpy.Exists(
            dataset
        )
    )


# ---------------------------------------------------------------------
# Main standalone evaluation
# ---------------------------------------------------------------------

def run_standalone_final_evaluation(
    context: Dict[str, Any],
    source_name: str,
    prediction_feature_class: Optional[
        str
    ] = None,
    output_json: Optional[
        str | Path
    ] = None,
) -> Dict[str, Any]:
    """
    Evaluate an existing Road prediction against the official
    independent test Ground Truth.

    Parameters
    ----------
    context:
        Prepared experiment context.

    source_name:
        aerial
        satellite
        drone

    prediction_feature_class:
        Optional explicit Road polygon prediction.

        When omitted, the prediction generated by the final inference
        stage is discovered automatically.

    output_json:
        Optional output JSON path.

    Returns
    -------
    dict
        Strict GIS evaluation result.
    """

    source_name = str(
        source_name
    ).lower()

    if source_name not in {
        "aerial",
        "satellite",
        "drone",
    }:

        raise ValueError(
            "source_name must be aerial, satellite, or drone."
        )

    # --------------------------------------------------------------
    # Verify frozen experiment
    # --------------------------------------------------------------

    frozen_settings = (
        load_frozen_final_settings(
            context=context,

            verify_checkpoint=True,
        )
    )

    if (
        source_name
        not in frozen_settings[
            "final_test_sources"
        ]
    ):

        raise RuntimeError(
            f"{source_name!r} is not part of the frozen "
            "final-test source list."
        )

    # --------------------------------------------------------------
    # Resolve official independent test data
    # --------------------------------------------------------------

    paths_config = (
        load_paths_config()
    )

    test_zone_config = (
        load_test_zone_config()
    )

    source_config = (
        resolve_final_test_source(
            source_name=source_name,

            paths_config=paths_config,

            test_zone_config=(
                test_zone_config
            ),
        )
    )

    if not source_config[
        "ready"
    ]:

        raise RuntimeError(
            f"{source_name.capitalize()} independent test is not "
            "fully configured:\n"
            + "\n".join(
                source_config[
                    "reasons_not_ready"
                ]
            )
        )

    test_raster = source_config[
        "image_path"
    ]

    ground_truth = source_config[
        "ground_truth_path"
    ]

    if not _arcgis_exists(
        test_raster
    ):

        raise FileNotFoundError(
            "Independent test raster does not exist:\n"
            f"{test_raster}"
        )

    if not _arcgis_exists(
        ground_truth
    ):

        raise FileNotFoundError(
            "Independent Road Ground Truth does not exist:\n"
            f"{ground_truth}"
        )

    # --------------------------------------------------------------
    # Resolve prediction
    # --------------------------------------------------------------

    if prediction_feature_class is None:

        prediction_feature_class = (
            load_prediction_from_final_inference(
                context=context,

                source_name=(
                    source_name
                ),
            )
        )

    prediction_feature_class = str(
        prediction_feature_class
    )

    if not _arcgis_exists(
        prediction_feature_class
    ):

        raise FileNotFoundError(
            "Prediction feature class does not exist:\n"
            f"{prediction_feature_class}"
        )

    # --------------------------------------------------------------
    # Output geodatabase
    # --------------------------------------------------------------

    output_geodatabase = (
        resolve_output_geodatabase(
            paths_config
        )
    )

    # --------------------------------------------------------------
    # Evaluation output
    # --------------------------------------------------------------

    output_folder = (
        Path(
            context[
                "output_folder"
            ]
        )
        / "final_test"
        / source_name
    )

    output_folder.mkdir(
        parents=True,
        exist_ok=True,
    )

    if output_json is None:

        output_json = (
            output_folder
            / "standalone_final_evaluation.json"
        )

    output_json = Path(
        output_json
    )

    evaluation_name = (
        f"{context['experiment_config']['experiment_id']}_"
        f"{source_name}_strict_eval"
    )

    # ArcGIS-safe conservative name.
    evaluation_name = (
        evaluation_name
        .replace(
            "-",
            "_",
        )
        .replace(
            " ",
            "_",
        )
    )

    # --------------------------------------------------------------
    # Strict GIS evaluation
    #
    # The independent raster defines the evaluation footprint.
    # --------------------------------------------------------------

    result = (
        evaluate_polygon_prediction(
            prediction_feature_class=(
                prediction_feature_class
            ),

            ground_truth_feature_class=(
                ground_truth
            ),

            output_geodatabase=(
                output_geodatabase
            ),

            evaluation_name=(
                evaluation_name
            ),

            evaluation_raster=(
                test_raster
            ),

            save_json_path=(
                output_json
            ),
        )
    )

    # --------------------------------------------------------------
    # Add experiment provenance
    # --------------------------------------------------------------

    metrics = result[
        "metrics"
    ]

    result[
        "experiment_id"
    ] = context[
        "experiment_config"
    ][
        "experiment_id"
    ]

    result[
        "source"
    ] = source_name

    result[
        "independent_test_raster"
    ] = test_raster

    result[
        "independent_ground_truth"
    ] = ground_truth

    result[
        "prediction_feature_class"
    ] = prediction_feature_class

    result[
        "frozen_checkpoint"
    ] = frozen_settings[
        "checkpoint"
    ][
        "path"
    ]

    result[
        "frozen_checkpoint_sha256"
    ] = frozen_settings[
        "checkpoint"
    ][
        "sha256"
    ]

    result[
        "frozen_probability_threshold"
    ] = float(
        frozen_settings[
            "inference"
        ][
            "probability_threshold"
        ]
    )

    result[
        "frozen_postprocessing"
    ] = frozen_settings[
        "postprocessing"
    ]

    result[
        "ground_truth_usage"
    ] = "evaluation_only"

    result[
        "parameter_search_performed"
    ] = False

    result[
        "source_specific_retuning"
    ] = False

    result[
        "final_test_used_for_selection"
    ] = False

    # --------------------------------------------------------------
    # Rewrite JSON with full provenance
    # --------------------------------------------------------------

    save_json(
        result,
        output_json,
    )

    # --------------------------------------------------------------
    # Console
    # --------------------------------------------------------------

    print()
    print(
        "=" * 72
    )

    print(
        f"STRICT FINAL GIS EVALUATION — {source_name.upper()}"
    )

    print(
        "=" * 72
    )

    print(
        f"Prediction       : "
        f"{prediction_feature_class}"
    )

    print(
        f"Test raster      : "
        f"{test_raster}"
    )

    print(
        f"Ground Truth     : "
        f"{ground_truth}"
    )

    print(
        "-" * 72
    )

    print(
        f"IoU              : "
        f"{metrics['iou_percent']:.4f}%"
    )

    print(
        f"Precision        : "
        f"{metrics['precision_percent']:.4f}%"
    )

    print(
        f"Recall           : "
        f"{metrics['recall_percent']:.4f}%"
    )

    print(
        f"F1               : "
        f"{metrics['f1_percent']:.4f}%"
    )

    print(
        "-" * 72
    )

    print(
        "GT usage         : EVALUATION ONLY"
    )

    print(
        "Retuning         : NO"
    )

    print(
        f"Result JSON      : "
        f"{output_json}"
    )

    print(
        "=" * 72
    )

    return result